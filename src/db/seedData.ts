export async function initializeDatabaseSeed(forceReload = false) {
  const count = await db.products.count();
  if (count === 0 || forceReload) {
    await db.products.clear();
    await db.suppliers.clear();
    await db.customers.clear();
    await db.sales.clear();
    await db.expenses.clear();
    await db.purchases.clear();
    await db.stockMovements.clear();

    await db.suppliers.bulkAdd(initialSuppliers);
    await db.customers.bulkAdd(initialCustomers);
    await db.products.bulkAdd(initialProducts);
    await db.sales.bulkAdd(initialSales);
    await db.expenses.bulkAdd(initialExpenses);
    await db.purchases.bulkAdd(initialPurchases);
    await db.stockMovements.bulkAdd(initialMovements);
    console.log('Database seeded with 29 DOM-extracted e-commerce lighting fixtures and real photos!');
  } else {
    // Check if products have the new DOM-extracted catalog (identified by prod-ch-1)
    const existing = await db.products.toArray();
    const hasNewCatalog = existing.some(p => p.id === 'prod-ch-1');
    if (!hasNewCatalog || existing.length !== initialProducts.length) {
      await db.products.clear();
      await db.products.bulkAdd(initialProducts);
      console.log('Automatically synchronized local database to the 29 DOM-extracted lighting catalog and photos!');
    }
  }
}
